# Generates the version header used by Core/ToDoList/ToDoList.rc.
#
# version.txt holds the last released version (2-3 components). The fourth
# component is derived from git as the number of commits made since version.txt
# was last changed, so a built binary automatically shows how far the code has
# moved past the release without requiring a counter file to be committed.

[CmdletBinding()]
param(
    [string]$Output = ""
)

$ErrorActionPreference = 'Stop'

$root = Split-Path -Parent $PSScriptRoot
$versionFile = Join-Path $root 'version.txt'
$rcFile = Join-Path $root 'Core\ToDoList\ToDoList.rc'

if (-not (Test-Path -LiteralPath $versionFile)) {
    throw "version.txt not found at $versionFile"
}

$raw = (Get-Content -LiteralPath $versionFile -Raw).Trim()
if (-not $raw) {
    throw "version.txt is empty"
}

$parts = @($raw -split '\.')
if (($parts.Count -lt 2) -or ($parts.Count -gt 4)) {
    throw "version.txt must contain 2 to 4 dot-separated numbers, found '$raw'"
}

$numbers = @()
foreach ($part in $parts) {
    $value = 0
    if (-not [int]::TryParse($part.Trim(), [ref]$value) -or ($value -lt 0)) {
        throw "version.txt contains a non-numeric component '$part'"
    }
    $numbers += $value
}

$explicitBuild = ($parts.Count -eq 4)

while ($numbers.Count -lt 4) {
    $numbers += 0
}

function Get-CommitCountSinceVersion {
    $git = Get-Command git -ErrorAction SilentlyContinue
    if (-not $git) {
        return 0
    }

    try {
        $last = & git -C $root log -1 --format=%H -- version.txt 2>$null
        if (($LASTEXITCODE -ne 0) -or (-not $last)) {
            return 0
        }

        $count = & git -C $root rev-list --count "$($last.Trim())..HEAD" 2>$null
        if (($LASTEXITCODE -ne 0) -or (-not $count)) {
            return 0
        }

        return [int]$count.Trim()
    }
    catch {
        return 0
    }
}

$build = if ($explicitBuild) { $numbers[3] } else { Get-CommitCountSinceVersion }

$major = $numbers[0]
$minor = $numbers[1]
$patch = $numbers[2]

$version = "$major.$minor.$patch.$build"
$versionComma = "$major, $minor, $patch, $build"

$content = @"
#ifndef TDL_VERSION_H
#define TDL_VERSION_H

// Generated by tools/version.ps1 from version.txt - do not edit

#define TDL_VER_MAJOR $major
#define TDL_VER_MINOR $minor
#define TDL_VER_PATCH $patch
#define TDL_VER_BUILD $build

#define TDL_VER_FILEVERSION $versionComma

#define TDL_VER_FILEVERSION_STR "$version"
#define TDL_VER_PRODUCTVERSION_STR "$versionComma"

#endif
"@
$content = ($content -replace "`r?`n", "`r`n") + "`r`n"

Write-Output "Version: $version"

if (-not $Output) {
    return
}

$writing = $true

if (Test-Path -LiteralPath $Output) {
    $existing = Get-Content -LiteralPath $Output -Raw
    if ($existing -and ($existing -ceq $content)) {
        $writing = $false
    }
}

if (-not $writing) {
    return
}

$outDir = Split-Path -Parent $Output
if ($outDir -and -not (Test-Path -LiteralPath $outDir)) {
    New-Item -ItemType Directory -Path $outDir -Force | Out-Null
}

Set-Content -LiteralPath $Output -Value $content -Encoding Ascii -NoNewline

# rc.exe has no reliable header dependency tracking, so make sure a changed
# version forces the resource to be recompiled.
if (Test-Path -LiteralPath $rcFile) {
    (Get-Item -LiteralPath $rcFile).LastWriteTime = Get-Date
}
